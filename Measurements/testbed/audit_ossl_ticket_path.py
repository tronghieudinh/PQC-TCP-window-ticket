#!/usr/bin/env python3
"""L1 item 6: is the path that writes the TLS 1.3 session ticket the same in the OpenSSL versions we measured (3.5.4, 3.5.9, 3.6.5, 4.1.0)?
Downloads ssl/statem/statem_srvr.c of each release tag from github.com/openssl/openssl, cuts out three pieces with a brace matcher, strips comments and
blank lines, and compares the text with the 3.5.4 baseline:
  1. ossl_statem_server13_write_transition, case TLS_ST_SR_FINISHED   (what the server writes after the client's Finished)
  2. ossl_statem_server_post_work, case TLS_ST_SW_SESSION_TICKET      (the flush after the ticket is built: statem_flush)
  3. tls_construct_new_session_ticket                                 (how the ticket message is built)
Output: results/ossl_ticket_path_audit.txt (with the sha256 of each source file). Needs network access; the output is shipped, not regenerated by reproduce_l1.sh.
Run: python3 Measurements/testbed/audit_ossl_ticket_path.py
"""
import difflib, hashlib, os, re, urllib.request
HERE = os.path.dirname(os.path.abspath(__file__))
V = ["3.5.4", "3.5.9", "3.6.5", "4.1.0"]
URL = "https://raw.githubusercontent.com/openssl/openssl/openssl-%s/ssl/statem/statem_srvr.c"

def fn(src, name):
    for m in re.finditer(r"\b" + re.escape(name) + r"\(", src):
        j = src.find("{", m.start()); semi = src.find(";", m.start())
        if j == -1 or (semi != -1 and semi < j): continue
        d = 0
        for k in range(j, len(src)):
            d += (src[k] == "{") - (src[k] == "}")
            if d == 0: return src[m.start():k + 1]

def norm(t):
    t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
    t = re.sub(r"\s+", " ", t)                      # layout differences (line breaks, indentation) are not changes
    return [x.strip() for x in re.split(r"(?<=[;{}])", t) if x.strip()]

def case(f, label):
    i = f.index("case " + label + ":"); n = re.search(r"\n    case ", f[i + 5:])
    return f[i:i + 5 + n.start()] if n else f[i:]

src = {v: urllib.request.urlopen(URL % v, timeout=60).read().decode() for v in V}
parts = {"server13 write transition after the client Finished": lambda s: norm(case(fn(s, "ossl_statem_server13_write_transition"), "TLS_ST_SR_FINISHED")),
         "post work after the ticket is built (flush)": lambda s: norm(case(fn(s, "ossl_statem_server_post_work"), "TLS_ST_SW_SESSION_TICKET")),
         "tls_construct_new_session_ticket": lambda s: norm(fn(s, "tls_construct_new_session_ticket"))}
out = ["statem_srvr.c of the release tags (sha256, first 16 hex): " + ", ".join(f"{v} {hashlib.sha256(src[v].encode()).hexdigest()[:16]}" for v in V), ""]
for name, f in parts.items():
    base = f(src[V[0]]); out.append(f"== {name} ({len(base)} statements in {V[0]})")
    for v in V[1:]:
        cur = f(src[v])
        d = [l for l in difflib.unified_diff(base, cur, lineterm="", n=0) if not l.startswith(("---", "+++", "@@"))]
        out.append(f"  {V[0]} -> {v}: {'identical' if not d else str(len(d)) + ' changed statements'}")
        out += ["      " + l[:150] for l in d[:24]]
open(os.path.join(HERE, "results", "ossl_ticket_path_audit.txt"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
